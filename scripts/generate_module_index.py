#!/usr/bin/env python3
"""Generate modules/index.md for both EN and ZH docs from manifest + config.

Reads ``manifest.json`` for runtime data (version, last_updated, deps) and
``scripts/module_index_config.yaml`` for doc-specific metadata (categories,
descriptions, benchmarks).  Produces deterministic markdown that can be
diffed or checked in CI with ``--check``.

Usage::

    python scripts/generate_module_index.py            # write both index files
    python scripts/generate_module_index.py --check     # exit 1 if files differ
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def _import_yaml_load():
    """Import the project's own yaml parser, avoiding stdlib name collision."""
    spec = importlib.util.spec_from_file_location(
        "zerodep_yaml", REPO_ROOT / "yaml" / "yaml.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.load


yaml_load = _import_yaml_load()

