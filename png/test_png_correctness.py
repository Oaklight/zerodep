# PNG Round-trip (self-verification, no Pillow dependency)
# ============================================================================


class TestPngRoundTrip:
    """Encode -> decode round-trip with zerodep only."""

    @pytest.mark.parametrize("mode", MODES_8BIT)
    def test_roundtrip_8bit(self, mode):
        w, h = 48, 48
        _, pixels = _make_test_image(mode, w, h)
        original = Image(width=w, height=h, data=pixels, mode=mode)

        decoded = decode_png(encode_png(original))
        assert decoded.width == w
        assert decoded.height == h
        assert decoded.mode == mode
        assert decoded.bit_depth == 8
        _assert_pixels_equal(decoded.data, pixels)

    def test_roundtrip_16bit(self):
        w, h = 16, 16
        rng = random.Random(77)
        pixels = b"".join(
            struct.pack(">H", rng.randint(0, 65535)) for _ in range(w * h)
        )
        original = Image(width=w, height=h, data=pixels, mode="L", bit_depth=16)

        decoded = decode_png(encode_png(original))
        assert decoded.bit_depth == 16
        _assert_pixels_equal(decoded.data, pixels)

    @pytest.mark.parametrize("strategy", FILTER_STRATEGIES)
    def test_roundtrip_filters(self, strategy):
        w, h = 32, 32
        _, pixels = _make_test_image("RGBA", w, h)
        original = Image(width=w, height=h, data=pixels, mode="RGBA")

        decoded = decode_png(encode_png(original, filter_strategy=strategy))
        _assert_pixels_equal(decoded.data, pixels, f"filter={strategy}")

    def test_roundtrip_metadata(self):
        w, h = 4, 4
        _, pixels = _make_test_image("L", w, h)
        meta = {"Author": "test", "Description": "round-trip metadata test"}
        original = Image(width=w, height=h, data=pixels, mode="L", metadata=meta)

        decoded = decode_png(encode_png(original))
        assert decoded.metadata == meta


