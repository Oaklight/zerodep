# ============================================================================
# Helpers
# ============================================================================


def _make_test_image(mode, width, height, seed=42):
    """Create a deterministic test image. Returns (PILImage, raw_pixels)."""
    rng = random.Random(seed)
    bpp = {"L": 1, "LA": 2, "RGB": 3, "RGBA": 4}[mode]
    pixels = bytes(rng.randint(0, 255) for _ in range(width * height * bpp))
    pil = PIL_Image.frombytes(mode, (width, height), pixels)
    return pil, pixels


def _pil_to_png(pil_img):
    buf = io.BytesIO()
    pil_img.save(buf, format="PNG")
    return buf.getvalue()


def _pil_to_bmp(pil_img):
    buf = io.BytesIO()
    pil_img.save(buf, format="BMP")
    return buf.getvalue()


def _assert_pixels_equal(actual, expected, msg=""):
    assert len(actual) == len(expected), (
        f"length mismatch{': ' + msg if msg else ''}: {len(actual)} vs {len(expected)}"
    )
    if actual != expected:
        idx = next(i for i, (a, b) in enumerate(zip(actual, expected)) if a != b)
        pytest.fail(
            f"pixel mismatch{': ' + msg if msg else ''} "
            f"at byte {idx}: {actual[idx]} vs {expected[idx]}"
        )


# ============================================================================
# PNG Decode — Pillow-generated PNGs decoded by zerodep
# ============================================================================

MODES_8BIT = ["L", "LA", "RGB", "RGBA"]
SIZES = [(1, 1), (8, 8), (64, 64), (256, 256)]


class TestPngDecodeVsPillow:
    """Decode Pillow-generated PNGs with zerodep, compare pixel data."""

    @pytest.mark.parametrize("mode", MODES_8BIT)
    @pytest.mark.parametrize("size", SIZES, ids=lambda s: f"{s[0]}x{s[1]}")
    def test_decode_8bit(self, mode, size):
        w, h = size
        pil, expected = _make_test_image(mode, w, h)
        png_bytes = _pil_to_png(pil)

        img = decode_png(png_bytes)
        assert img.width == w
        assert img.height == h
        assert img.mode == mode
        assert img.bit_depth == 8
        _assert_pixels_equal(img.data, expected, f"{mode} {w}x{h}")

    def test_decode_16bit_gray(self):
        """16-bit grayscale PNG generated by Pillow."""
        w, h = 32, 32
        rng = random.Random(99)
        values = [rng.randint(0, 65535) for _ in range(w * h)]

        # Pillow I;16 uses little-endian storage
        le_bytes = b"".join(struct.pack("<H", v) for v in values)
        pil = PIL_Image.frombytes("I;16", (w, h), le_bytes)
        png_bytes = _pil_to_png(pil)

        img = decode_png(png_bytes)
        assert img.mode == "L"
        assert img.bit_depth == 16

        # PNG stores 16-bit as big-endian
        expected_be = b"".join(struct.pack(">H", v) for v in values)
        _assert_pixels_equal(img.data, expected_be, "16-bit L")


# ============================================================================
# PNG Encode — zerodep encodes, Pillow decodes to verify
# ============================================================================

FILTER_STRATEGIES = ["auto", "none", "sub", "up", "avg", "paeth"]


class TestPngEncodeVsPillow:
    """Encode with zerodep, decode with Pillow, compare pixel data."""

    @pytest.mark.parametrize("mode", MODES_8BIT)
    @pytest.mark.parametrize("strategy", FILTER_STRATEGIES)
    def test_encode_filter_strategies(self, mode, strategy):
        w, h = 32, 32
        _, pixels = _make_test_image(mode, w, h)
        img = Image(width=w, height=h, data=pixels, mode=mode)

        png_bytes = encode_png(img, filter_strategy=strategy)
        pil = PIL_Image.open(io.BytesIO(png_bytes))
        assert pil.mode == mode
        _assert_pixels_equal(pil.tobytes(), pixels, f"{mode} filter={strategy}")

    @pytest.mark.parametrize("size", SIZES, ids=lambda s: f"{s[0]}x{s[1]}")
    def test_encode_rgba_sizes(self, size):
        w, h = size
        _, pixels = _make_test_image("RGBA", w, h)
        img = Image(width=w, height=h, data=pixels, mode="RGBA")

        png_bytes = encode_png(img)
        pil = PIL_Image.open(io.BytesIO(png_bytes))
        _assert_pixels_equal(pil.tobytes(), pixels, f"RGBA {w}x{h}")

    def test_encode_metadata(self):
        """tEXt metadata survives encode -> Pillow decode."""
        w, h = 8, 8
        _, pixels = _make_test_image("L", w, h)
        meta = {"Author": "zerodep", "Comment": "test image"}
        img = Image(width=w, height=h, data=pixels, mode="L", metadata=meta)

        png_bytes = encode_png(img)
        pil = PIL_Image.open(io.BytesIO(png_bytes))
        pil_text = getattr(pil, "text", {}) or pil.info
        for key, val in meta.items():
            assert pil_text.get(key) == val, f"metadata key {key!r} missing"


