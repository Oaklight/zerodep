class TestBmpEncodeVsPillow:
    """Encode BMP with zerodep, decode with Pillow."""

    @pytest.mark.parametrize(
        "size",
        [(8, 8), (11, 5), (64, 64), (256, 256)],
        ids=lambda s: f"{s[0]}x{s[1]}",
    )
    def test_encode_rgb(self, size):
        w, h = size
        _, pixels = _make_test_image("RGB", w, h)
        img = Image(width=w, height=h, data=pixels, mode="RGB")

        bmp_bytes = encode_bmp(img)
        pil = PIL_Image.open(io.BytesIO(bmp_bytes)).convert("RGB")
        _assert_pixels_equal(pil.tobytes(), pixels, f"BMP encode RGB {w}x{h}")

    def test_encode_rgba(self):
        # BMP with 40-byte DIB header has no alpha mask — Pillow reads the
        # 4th byte as reserved (sets alpha=255).  Compare RGB channels only.
        w, h = 32, 32
        _, pixels = _make_test_image("RGBA", w, h)
        img = Image(width=w, height=h, data=pixels, mode="RGBA")

        bmp_bytes = encode_bmp(img)
        pil = PIL_Image.open(io.BytesIO(bmp_bytes)).convert("RGB")
        expected_rgb = bytes(
            pixels[i + c] for i in range(0, len(pixels), 4) for c in range(3)
        )
        _assert_pixels_equal(pil.tobytes(), expected_rgb, "BMP encode RGBA (RGB only)")


