# ============================================================================
# Mode conversion vs Pillow
# ============================================================================

# Conversions where both implementations should match exactly (no luminosity)
EXACT_CONVERSIONS = [
    ("L", "RGB"),
    ("L", "RGBA"),
    ("L", "LA"),
    ("LA", "L"),
    ("RGB", "RGBA"),
    ("RGBA", "RGB"),
]

# Conversions involving luminosity — allow +/-1 rounding difference
APPROX_CONVERSIONS = [
    ("RGB", "L"),
    ("RGB", "LA"),
    ("RGBA", "L"),
    ("RGBA", "LA"),
    ("LA", "RGB"),
    ("LA", "RGBA"),
]


class TestConvert:
    """Test mode conversion against Pillow's convert."""

    @pytest.mark.parametrize("src,dst", EXACT_CONVERSIONS)
    def test_exact(self, src, dst):
        w, h = 16, 16
        pil, pixels = _make_test_image(src, w, h)
        img = Image(width=w, height=h, data=pixels, mode=src)

        converted = convert(img, dst)
        expected = pil.convert(dst).tobytes()
        _assert_pixels_equal(converted.data, expected, f"{src}->{dst}")

    @pytest.mark.parametrize("src,dst", APPROX_CONVERSIONS)
    def test_approx(self, src, dst):
        w, h = 16, 16
        pil, pixels = _make_test_image(src, w, h)
        img = Image(width=w, height=h, data=pixels, mode=src)

        converted = convert(img, dst)
        expected = pil.convert(dst).tobytes()
        max_diff = max(abs(a - b) for a, b in zip(converted.data, expected))
        assert max_diff <= 1, f"{src}->{dst} max pixel diff {max_diff} > 1"

    def test_noop(self):
        _, pixels = _make_test_image("RGB", 8, 8)
        img = Image(width=8, height=8, data=pixels, mode="RGB")
        result = convert(img, "RGB")
        _assert_pixels_equal(result.data, pixels)
        assert result is not img


