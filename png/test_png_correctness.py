# Matrix API
# ============================================================================


class TestMatrixApi:
    """Test matrix_to_png / png_to_matrix round-trips."""

    def test_uint8_roundtrip(self):
        matrix = [[i * 17 + j for j in range(16)] for i in range(15)]
        result = png_to_matrix(matrix_to_png(matrix))
        assert result == matrix

    def test_uint16_roundtrip(self):
        matrix = [[i * 4096 + j * 16 for j in range(32)] for i in range(16)]
        result = png_to_matrix(matrix_to_png(matrix, bit_depth=16))
        assert result == matrix

    def test_float_roundtrip_8bit(self):
        matrix = [[math.sin(x * 0.1 + y * 0.2) for x in range(32)] for y in range(32)]
        result = png_to_matrix(matrix_to_png(matrix))

        vmin = min(min(r) for r in matrix)
        vmax = max(max(r) for r in matrix)
        tol = (vmax - vmin) / 255 + 1e-9
        for y in range(len(matrix)):
            for x in range(len(matrix[0])):
                assert abs(result[y][x] - matrix[y][x]) <= tol

    def test_float_roundtrip_16bit(self):
        matrix = [
            [math.sin(x * 0.1 + y * 0.2) * 1000 for x in range(16)] for y in range(16)
        ]
        result = png_to_matrix(matrix_to_png(matrix, bit_depth=16))

        vmin = min(min(r) for r in matrix)
        vmax = max(max(r) for r in matrix)
        tol = (vmax - vmin) / 65535 + 1e-9
        for y in range(len(matrix)):
            for x in range(len(matrix[0])):
                assert abs(result[y][x] - matrix[y][x]) <= tol

    def test_constant_matrix(self):
        matrix = [[42] * 8 for _ in range(8)]
        result = png_to_matrix(matrix_to_png(matrix))
        assert result == matrix

    def test_negative_values(self):
        matrix = [[-10, 0, 10], [-5, 5, 15]]
        result = png_to_matrix(matrix_to_png(matrix))
        assert isinstance(result[0][0], float)

    def test_empty_raises(self):
        with pytest.raises(EncodeError):
            matrix_to_png([])
        with pytest.raises(EncodeError):
            matrix_to_png([[]])


