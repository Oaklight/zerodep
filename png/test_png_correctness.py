# Error cases
# ============================================================================


class TestErrorCases:
    """Invalid inputs raise appropriate errors."""

    def test_truncated_png(self):
        _, pixels = _make_test_image("RGB", 8, 8)
        png_bytes = encode_png(Image(width=8, height=8, data=pixels, mode="RGB"))
        with pytest.raises(DecodeError):
            decode_png(png_bytes[:20])

    def test_bad_png_signature(self):
        with pytest.raises(DecodeError, match="bad signature"):
            decode_png(b"NOT A PNG FILE" + b"\x00" * 100)

    def test_bad_bmp_signature(self):
        with pytest.raises(DecodeError, match="bad signature"):
            decode_bmp(b"XX" + b"\x00" * 100)

    def test_bmp_too_small(self):
        with pytest.raises(DecodeError):
            decode_bmp(b"BM" + b"\x00" * 10)

    def test_invalid_mode(self):
        with pytest.raises(ValueError, match="unsupported mode"):
            Image(width=1, height=1, data=b"\x00", mode="CMYK")

    def test_invalid_bit_depth(self):
        with pytest.raises(ValueError, match="unsupported bit_depth"):
            Image(width=1, height=1, data=b"\x00", mode="L", bit_depth=4)

    def test_data_length_mismatch(self):
        with pytest.raises(ValueError, match="data length"):
            Image(width=2, height=2, data=b"\x00\x01\x02", mode="L")

    def test_bmp_encode_unsupported_mode(self):
        img = Image(width=1, height=1, data=b"\x00", mode="L")
        with pytest.raises(EncodeError, match="RGB or RGBA"):
            encode_bmp(img)

    def test_encode_unknown_filter(self):
        img = Image(width=1, height=1, data=b"\x00\x00\x00", mode="RGB")
        with pytest.raises(EncodeError, match="unknown filter_strategy"):
            encode_png(img, filter_strategy="invalid")

    def test_convert_unsupported_target(self):
        img = Image(width=1, height=1, data=b"\x00", mode="L")
        with pytest.raises(ValueError, match="unsupported target mode"):
            convert(img, "CMYK")

    def test_convert_16bit_raises(self):
        pixels = struct.pack(">H", 1000)
        img = Image(width=1, height=1, data=pixels, mode="L", bit_depth=16)
        with pytest.raises(ValueError, match="8-bit"):
            convert(img, "RGB")
